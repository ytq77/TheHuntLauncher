"""Generate a text-only Simplified Chinese BBSC build from the fixed upstream table."""
import json
from pathlib import Path
import re
from localize_windows import generate as generate_windows

import sys
WORK = Path(sys.argv[1]).resolve() / "emulator/src/core"
SOURCE = WORK
LITERAL = r'"(?:[^"\\\r\n]|\\.)*"'
ENTRY = re.compile(r'^\{(\d+), (\d+), u(' + LITERAL + r')\}', re.M)
UTF16 = re.compile(r'(?<![\w])u' + LITERAL + r'(?:\s*u' + LITERAL + r')*')
TAGS = re.compile(r'<\?[^?]+\?>')
catalog = json.loads((Path(__file__).resolve().parents[1] / "locales/zh-CN.json").read_text(encoding="utf-8"))


def translate(text):
    if text in catalog:
        return catalog[text]
    match = re.fullmatch(r'The host started the battle against\n(<\?npcNameId@\d+\?>)\.', text)
    if match:
        return "唤你而来的猎人\n正与" + match[1] + "交战。"
    match = re.fullmatch(r'(<\?npcNameId@\d+\?>) defeated\.', text)
    if match:
        return "已猎杀" + match[1] + "。"
    raise ValueError("Missing translation: " + repr(text))


def cpp(text):
    return 'u' + json.dumps(text, ensure_ascii=True)


def main():
    original = (SOURCE / "bbsc_messages.inc").read_text(encoding="utf-8")
    rows = [(int(m[1]), int(m[2]), json.loads(m[3])) for m in ENTRY.finditer(original)]
    if len(rows) != 210 or len({(c, i) for c, i, _ in rows}) != 210:
        raise ValueError("Unexpected upstream text table; recheck source before building.")
    generated = ["// Generated by localize-bbsc.py; local zh-CN catalog. Keep IDs and game tags unchanged."]
    translated_rows = []
    for category, msg_id, text in rows:
        translated = translate(text)
        assert TAGS.findall(text) == TAGS.findall(translated), (category, msg_id)
        assert any('\u4e00' <= c <= '\u9fff' for c in translated), (category, msg_id)
        generated.append(f'{{{category}, {msg_id}, {cpp(translated)}}},')
        translated_rows.append({"category": category, "id": msg_id, "text": translated})
    (WORK / "bbsc_messages_zh_cn.inc").write_text("\n".join(generated) + "\n", encoding="utf-8")

    source = (SOURCE / "bloodborne_re.cpp").read_text(encoding="utf-8")
    assert source.count('#include "bbsc_messages.inc"') == 1
    source = source.replace('#include "bbsc_messages.inc"', '#include "bbsc_messages_zh_cn.inc"')
    changes = []
    def replace_literal(match):
        literals = re.findall('u(' + LITERAL + ')', match[0])
        text = ''.join(json.loads(value) for value in literals)
        if text in ("\n", ", "):
            return match[0]
        translated = translate(text)
        changes.append({"source": text, "text": translated})
        return cpp(translated)
    source = UTF16.sub(replace_literal, source)
    before = '''        const std::string text = name != nullptr
                                     ? fmt::format("The host started the battle against\\n{}.", name)
                                     : std::string{"The host started a boss battle."};'''
    after = '''        std::u16string text = u"唤你而来的猎人已与强敌交战。";
        if (name != nullptr) {
            text = u"唤你而来的猎人\\n正与";
            const std::string tag = fmt::format("<?npcNameId@{}?>", boss);
            for (const unsigned char ch : tag) {
                text.push_back(ch);
            }
            text += u"交战。";
        }'''
    assert source.count(before) == 1, "Unexpected dynamic boss notice implementation"
    source = source.replace(before, after)
    assert source.count('bbsc_boss_line_text[i] = static_cast<unsigned char>(text[i]);') == 1
    source = source.replace('bbsc_boss_line_text[i] = static_cast<unsigned char>(text[i]);',
                            'bbsc_boss_line_text[i] = text[i];')
    (WORK / "bloodborne_re_zh_cn.cpp").write_text(source, encoding="utf-8")
    report = {"entries": translated_rows, "literal_changes": changes,
              "dynamic_boss_notice": "UTF-16 with original npcNameId tag; names supplied by game's own language"}
    (WORK / "zh-cn-validation.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    windows = generate_windows(WORK.parents[1] / "mod", Path(__file__).resolve().parents[1] / "locales/windows-zh-CN.json")
    (WORK / "windows-zh-cn-validation.json").write_text(json.dumps(windows, indent=2), encoding="utf-8")
    print(f"Generated {len(rows)} message entries; {len(changes)} on-screen literals; all original IDs/tags preserved.")
    print(f"Generated {windows['catalog_entries']} Windows text entries ({windows['translated_occurrences']} occurrences).")


if __name__ == "__main__":
    main()
