#!/usr/bin/env bash
set -euo pipefail
cd -- "$(dirname -- "$0")/.."
root="$PWD"
src="$root/.build/bbsc/emulator"
port="${BBSC_PORT_SOURCE:-$root/.build/bbport}"
out="$root/.build/mod"
mkdir -p "$out"
flags=(-std=c++23 -O2 -g -fms-extensions -DNOMINMAX -DWIN32_LEAN_AND_MEAN
       -D_CRT_SECURE_NO_WARNINGS -DBBSC_MOD -DFMT_HEADER_ONLY
       -I"$src/mod/shim" -I"$src/src" -I"$port/gpu/third_party/xbyak")
if [[ "${BBSC_J4_DIAG_DISABLED:-0}" == 1 ]]; then flags+=(-DBBSC_J4_DIAG_DISABLED); fi
objects=()
for name in bbsc_mod bbsc_hooks bbsc_relay bbsc_channel bbsc_http bbsc_discord; do
    source="$src/mod/$name.cpp"
    if [[ "$name" == bbsc_mod ]]; then source="$src/mod/bbsc_mod_zh_cn.cpp"; fi
    clang++ "${flags[@]}" -c "$source" -o "$out/$name.o"
    objects+=("$out/$name.o")
done
for name in bbsc_memscan bloodborne_re_zh_cn; do
    clang++ "${flags[@]}" -c "$src/src/core/$name.cpp" -o "$out/$name.o"
    objects+=("$out/$name.o")
done
clang++ -shared "${objects[@]}" -o "$out/bbsc.dll" -lws2_32 -lwinhttp -luser32 -lbcrypt
clang++ "${flags[@]}" "$src/mod/bbsc_launch_zh_cn.cpp" -o "$out/bbsc-launch.exe" \
    -municode -mwindows -luser32 -lcomdlg32
# Check serial sign cleanup without starting the game or touching real saves.
clang++ -std=c++23 -O2 tests/test_summon_cleanup.cpp -o "$out/test-summon-cleanup.exe"
"$out/test-summon-cleanup.exe"
clang++ "${flags[@]}" tests/test_summon_cleanup_http.cpp -o "$out/test-summon-cleanup-http.exe" -lwinhttp
"$out/test-summon-cleanup-http.exe" "$out/summon-cleanup-fixture-$(date +%s%N)"
# Exercise the real safe scanner against changing page permissions and region boundaries.
clang++ -std=c++23 -fms-extensions -I"$src/src" \
    '-DBBSC_SCAN_SOURCE="../patches/bbsc_memscan.cpp"' tests/test_memscan.cpp -o "$out/test-memscan.exe"
"$out/test-memscan.exe"
"$out/test-memscan.exe" race
clang++ -std=c++23 tests/test_banner_diagnostics.cpp -o "$out/test-banner.exe"
"$out/test-banner.exe"
clang++ -std=c++23 tests/test_summon_type.cpp -o "$out/test-summon-type.exe"
"$out/test-summon-type.exe"
clang++ -std=c++23 tests/test_blank_menu.cpp -o "$out/test-blank-menu.exe"
"$out/test-blank-menu.exe"
clang++ -std=c++23 tests/test_insight_refund.cpp -o "$out/test-insight-refund.exe"
"$out/test-insight-refund.exe"
clang++ -std=c++23 tests/test_empty_host_cancel.cpp -o "$out/test-empty-host-cancel.exe"
"$out/test-empty-host-cancel.exe"
clang++ -std=c++23 tests/test_empty_host_cancel_runtime.cpp -o "$out/test-empty-host-cancel-runtime.exe"
"$out/test-empty-host-cancel-runtime.exe"
clang++ -std=c++23 tests/test_guest_return.cpp -o "$out/test-guest-return.exe"
"$out/test-guest-return.exe"
clang++ -std=c++23 tests/test_coop_effect_restore.cpp -o "$out/test-coop-effect-restore.exe"
"$out/test-coop-effect-restore.exe"
python scripts/check_j4_diag_slots.py "$src" "$out/j4-slot-ownership.json" "$out/j4_channel_fixture.inc"
clang++ -std=c++23 -O2 -I"$out" tests/test_j4_diag.cpp -o "$out/test-j4-diag.exe"
"$out/test-j4-diag.exe" "$out/j4-diag-fixture-$(date +%s%N)"
python scripts/test_join_cause.py --root "$root" --output "$out/join-cause"
python scripts/test_boss_spectate.py "$src/src/core/bloodborne_re_zh_cn.cpp"
python scripts/test_wipe_respawn.py "$root" "$out/wipe-respawn"
python scripts/test_death_entry_paths.py "$root" "$out/death-entry-paths"
# Private local native-fragment validation; the game ELF and generated bytes are never packaged.
prompt_elf_args=()
if [[ -n "${BB_EBOOT_ELF+x}" ]]; then
    prompt_elf_args=(--elf "$BB_EBOOT_ELF")
fi
# An explicit override must pass the generator's existing file/hash checks, even if empty.
if [[ -n "${BB_EBOOT_ELF+x}" || -f 'C:/bbsc-dev/experiment/baseline/out/eboot.elf' ]]; then
    python scripts/prepare_prompt_regressions.py --source "$root" --output "$out/prompt-regressions" --mode all "${prompt_elf_args[@]}"
    for kind in retained_join death_local_prompt; do
        clang++ "${flags[@]}" "$out/prompt-regressions/test_${kind}.cpp" -o "$out/prompt-regressions/test_${kind}.exe"
        "$out/prompt-regressions/test_${kind}.exe"
    done
else
    echo '跳过 prompt 原生回归：需要本机已校验的 CUSA03173 1.09 ELF'
fi
python scripts/prepare_guest_return_regression.py "$src/src/core/bloodborne_re_zh_cn.cpp" "$out/test-guest-return-session.cpp"
clang++ -std=c++23 "$out/test-guest-return-session.cpp" -o "$out/test-guest-return-session.exe"
"$out/test-guest-return-session.exe"
python scripts/prepare_guest_items_regression.py "$src/src/core/bloodborne_re_zh_cn.cpp" "$out/test-guest-items.cpp"
clang++ -std=c++23 "$out/test-guest-items.cpp" -o "$out/test-guest-items.exe"
for mode in closed drops home; do
    "$out/test-guest-items.exe" "$mode"
done
clang++ -std=c++23 tests/test_personal_rewards.cpp -o "$out/test-personal-rewards.exe"
"$out/test-personal-rewards.exe"
python scripts/prepare_personal_rewards_regression.py "$src/src/core/bloodborne_re_zh_cn.cpp" "$out/test-personal-rewards-runtime.cpp"
clang++ -std=c++23 -I"$src/src/core" "$out/test-personal-rewards-runtime.cpp" -o "$out/test-personal-rewards-runtime.exe"
"$out/test-personal-rewards-runtime.exe"
python scripts/prepare_npc_regression.py "$src/src/core/bloodborne_re_zh_cn.cpp" "$out/test-npc-prejoin.cpp"
clang++ -std=c++23 -DEXPECT_FIXED "$out/test-npc-prejoin.cpp" -o "$out/test-npc-prejoin.exe"
"$out/test-npc-prejoin.exe"
python scripts/prepare_gift_regression.py "$src/src/core/bloodborne_re_zh_cn.cpp" "$out/test-npc-gift.cpp"
clang++ -std=c++23 -DEXPECT_FIXED "$out/test-npc-gift.cpp" -o "$out/test-npc-gift.exe"
"$out/test-npc-gift.exe"
python scripts/prepare_kit_regression.py "$src/src/core/bloodborne_re_zh_cn.cpp" "$out/test-kit-initialization.cpp"
clang++ -std=c++23 "$out/test-kit-initialization.cpp" -o "$out/test-kit-initialization.exe"
for mode in pending null-repo missing-effect missing-goods readonly truncated-index fallback fresh backup-failure existing storage; do
    "$out/test-kit-initialization.exe" "$mode"
done
clang++ -std=c++23 tests/test_save_proof.cpp -o "$out/test-save-proof.exe" -lbcrypt
mkdir -p "$out/save-proof-fixture"
"$out/test-save-proof.exe" "$out/save-proof-fixture"
clang++ "${flags[@]}" tests/test_home_save_proof.cpp -o "$out/test-home-save-proof.exe" -lbcrypt
"$out/test-home-save-proof.exe" "$out/home-save-proof-$(date +%s%N)"
clang++ -std=c++23 tests/test_slot_guard.cpp -o "$out/test-slot-guard.exe"
for mode in noaccess unmapped null guest already protect-failure write-failure loader-change normal readonly race-protect race-decommit; do
    "$out/test-slot-guard.exe" "$mode"
done
clang++ "${flags[@]}" tests/test_menu_quit.cpp "$out/bbsc_hooks.o" -o "$out/test-menu-quit.exe"
for mode in valid mismatch stale active different-map guest host foreign-world invalid-global dead unwritable empty pending-mode stale-lamp observed-lamp active-lamp invalid-point cleared-lamp pending-info unknown-map; do
    "$out/test-menu-quit.exe" "$mode"
done
python scripts/test_world_recovery_native.py
python scripts/test_guest_travel_state.py "$src/src/core/bloodborne_re_zh_cn.cpp" "$out/guest-travel-state"
python scripts/test_join_placement.py "$src/src/core/bloodborne_re_zh_cn.cpp" "$out/test-join-placement.exe"
python scripts/prepare_game_hardening_regression.py "$src/src/core/bloodborne_re_zh_cn.cpp" "$out/game-hardening"
for kind in pvp kit lua relay; do
    clang++ -std=c++23 "$out/game-hardening/game_hardening_$kind.cpp" -o "$out/game-hardening/test-$kind.exe"
done
"$out/game-hardening/test-lua.exe"
for mode in host guest strict expired fresh-unbound wrong-room selection-switch packet-concurrency session restore removed reuse-actor reuse-member reuse-modules reuse-effects reuse-type reload invalid-list readonly native-reset loading relay-one relay-other-map relay-far relay-stale relay-future relay-nan relay-no-transform relay-native-nan relay-no-native-host relay-two-native-hosts relay-ambiguous relay-distant-other relay-loading relay-cross-map relay-leave relay-matching; do
    "$out/game-hardening/test-pvp.exe" "$mode"
done
for mode in fresh backup-failure fits-failure capacity-exhausted add-failure remove-failure flag-failure already-complete flag-only flag-manager same-address-reload storage guest not-ready; do
    "$out/game-hardening/test-kit.exe" "$mode"
done
for mode in selected wrong-sender not-hosting unselected self host-state-to-host legacy-request old-frame truncated; do
    "$out/game-hardening/test-relay.exe" "$mode"
done
python scripts/test_save_hardening.py --source "$root/.build/bbsc" --port "$port"
python scripts/prepare_save_bridge.py .build/bbsc .build/save-bridge
bridge="$root/.build/save-bridge"
clang++ "${flags[@]}" -I"$src/src/core" -I"$src/mod" -c "$bridge/bbsc_mod_save.cpp" -o "$bridge/bbsc_mod.o"
clang++ "${flags[@]}" -I"$src/src/core" -c "$bridge/bloodborne_re_save.cpp" -o "$bridge/bloodborne_re.o"
clang++ -shared "$bridge/bbsc_mod.o" "$bridge/bloodborne_re.o" \
    "$out/bbsc_hooks.o" "$out/bbsc_relay.o" "$out/bbsc_channel.o" "$out/bbsc_http.o" \
    "$out/bbsc_discord.o" "$out/bbsc_memscan.o" -o "$bridge/save-bridge.dll" -lws2_32 -lwinhttp -luser32 -lbcrypt
sha256sum "$out/bbsc.dll" "$out/bbsc-launch.exe" "$bridge/save-bridge.dll"
